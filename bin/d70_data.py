"""d70_data — the knowledge the interface is built on.

Kept out of the server so that d70-studio stays about plumbing and this file
stays about photography. Three tables:

    GEAR      every distinct piece of kit any project asks for
    PROJECTS  100 things to do with the camera, each declaring what it needs
    GLOSSARY  plain-language definitions, written for someone who has never
              owned a camera

A project's `runs` state is not stored anywhere. It is computed from the gear
the owner has ticked, so the project list stays honest as the kit grows.

`requires` is a list of requirements, all of which must be met. An entry that is
itself a list means "any one of these will do" — a telescope or a microscope, an
optical slave or a sync cord, a macro lens or a close-up dioptre. Without that,
the catalogue would either demand more than a project needs or quietly pretend
one substitute did not exist.
"""

